    items = f"{sum(ex.values())} ({ex['ARMOUR']}/{ex['WEAPON']}/{ex['CROSSBOW']})" if ex else "после подписки"
    slots = ", ".join(f"{k}:{v}" for k, v in sorted(r["armour_slots"].items(), key=lambda x: -x[1])[:4]) if r["armour_slots"] else "—"
