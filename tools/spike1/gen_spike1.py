"""Спайк 1: генерация KMM_Spike1.mod кодом (без FCS).

Покрывает типы записей из CORE.md §12.1: предметы, отряды, города/override, + фракция, персонаж,
world state, дельта к ванильной записи (изменение значения, добавление и удаление ссылки).
Пишет в C:\\KenshiModMap\\build\\spike1\\KMM_Spike1\\ — папку игры НЕ трогает.
"""
import json
import os
import sys

sys.path.insert(0, r"C:\KenshiModMap\tools")
import kmod  # noqa: E402
import fcsdef  # noqa: E402
from kmod import F32  # noqa: E402

KENSHI = r"C:\Program Files (x86)\Steam\steamapps\common\Kenshi"
DATA = KENSHI + r"\data"
CHAIN = ["gamedata.base", "Newwworld.mod", "Dialogue.mod", "rebirth.mod"]
NAME = "KMM_Spike1"
OUT_DIR = rf"C:\KenshiModMap\build\spike1\{NAME}"

# ванильные sid (найдены поиском по слитому контексту)
KATANA, LEATHER_SHIRT, STEEL_BARS = "476-gamedata.base", "1169-gamedata.base", "579-gamedata.base"
DUST_FACTION, DUST_BANDIT, DUST_SQUAD = "200-gamedata.base", "510-gamedata.base", "1302-gamedata.base"
BARK = "1076-gamedata.base"
UNITED_CITIES = "defaultEmpireFactionSID"

ctx = kmod.load_chain([os.path.join(DATA, f) for f in CHAIN])
mb = kmod.ModBuilder(f"{NAME}.mod", ctx, dependencies=CHAIN, author="KMM",
                     description="Spike 1: records generated by tools/kmod.py")

# 1) предметы: деградированные варианты (CORE.md §7, T0 «ржавчина»)
k0 = mb.new("WEAPON", "Katana [KMM T0 rusted]", template=KATANA, values={
    "cut damage multiplier": F32(0.7), "min cut damage mult": F32(0.6), "value": 120,
    "description": "Ржавый реликт. Сгенерировано KMM (спайк 1).",
})
a0 = mb.new("ARMOUR", "Leather Shirt [KMM T0 torn]", template=LEATHER_SHIRT, values={"value": 15})
relic = mb.new("ITEM", "KMM Relic Component", template=STEEL_BARS, values={
    "value": 2500, "description": "Тестовый товар-поток (спайк 1).",
})

# 2) фракция-клон
fac = mb.new("FACTION", "KMM Test Warband", template=DUST_FACTION)

# 3) персонаж + отряд с этим снаряжением и фракцией
grunt = mb.new("CHARACTER", "KMM Warband Grunt", template=DUST_BANDIT)
grunt.refs["weapons"] = [kmod.Ref(k0.sid, 1, 100, 0)]
grunt.refs["clothing"] = [kmod.Ref(a0.sid, 1, 100, 0)]
grunt.refs["faction"] = [kmod.Ref(fac.sid)]
squad = mb.new("SQUAD_TEMPLATE", "KMM Warband squad", template=DUST_SQUAD)
squad.refs["leader"] = [kmod.Ref(grunt.sid, 1, 0, 0)]
squad.refs["squad"] = [kmod.Ref(grunt.sid, 3, 6, 0)]
squad.refs["faction"] = [kmod.Ref(fac.sid)]
squad.refs["special items"] = [kmod.Ref(relic.sid, 1, 0, 0)]

# 4) world state + override города (механика CORE.md §11: якорь × вариант)
ws = mb.new("WORLD_EVENT_STATE", "KMM: Bark taken by warband (test)", values={
    "notes": "spike1: переключается ядром/условием", "player involvement": False,
}, refs={"town okay": [(BARK, 0, 0, 0)]})  # условие: Bark разрушен — в обычной игре ложно
ovr = mb.new("TOWN", "Bark (KMM override: warband)", template=BARK, values={
    "residents override": True, "distant mesh": False,
})
ovr.refs.pop("override town", None)   # override не наследует список override'ов
ovr.refs["faction"] = [kmod.Ref(fac.sid)]
ovr.refs["residents"] = [kmod.Ref(squad.sid, 2, 3, 0)]
ovr.refs["world state"] = [kmod.Ref(ws.sid, 1, 0, 0)]

# 5) дельты к ванили: Bark получает наш override; ванильный отряд меняет значение и теряет ссылку
mb.change(BARK, set_refs={"override town": [(ovr.sid, 0, 0, 0)]})
mb.change(DUST_SQUAD, values={"dont multiply": True}, del_refs={"dialog squad": ["17954-gamedata.base"]})

mod = mb.build()
os.makedirs(OUT_DIR, exist_ok=True)
path = os.path.join(OUT_DIR, f"{NAME}.mod")
data = kmod.write(mod, path)

# --- самопроверки -------------------------------------------------------------
back = kmod.read(path)
assert kmod.write(back) == data, "повторная запись не идентична"
import struct  # noqa: E402
f32 = lambda v: struct.unpack("<f", struct.pack("<f", v))[0] if isinstance(v, float) else v  # noqa: E731
sem = lambda m: [(i.sid, i.name, i.type, i.save_data, {k: f32(v) for k, v in i.values.items()}, i.refs)  # noqa: E731
                 for i in m.items]
for a, b in zip(sem(back), sem(mod), strict=True):
    assert a == b, f"чтение != записанному: {a[0]} {a[1]}"

kmod.apply(ctx, back)  # накладываем как игра
sch = fcsdef.load(KENSHI)
errors, warns = [], []
for it in back.items:
    e, w = fcsdef.validate(ctx.get(it.sid) or it, sch, resolve=ctx.get)
    errors += e; warns += w
assert ctx[BARK].refs["override town"][-1].target == ovr.sid
assert "17954-gamedata.base" not in [r.target for r in ctx[DUST_SQUAD].refs.get("dialog squad", [])]
assert ctx[DUST_SQUAD].values["dont multiply"] is True

dump = [{"sid": i.sid, "type": i.type_name, "name": i.name, "change": i.change,
         "nvalues": len(i.values), "refs": {k: len(v) for k, v in i.refs.items()}} for i in back.items]
json.dump(dump, open(r"C:\KenshiModMap\tools\spike1\out\kmod_dump.json", "w", encoding="utf-8"),
          ensure_ascii=False, indent=1)
print(f"{path}: {len(data)} байт, записей {len(back.items)}, lastId {back.last_id}")
for d in dump:
    print(f"  {d['change']} {d['type']:<18} {d['sid']:<22} {d['name']}")
print(f"валидация fcs.def: ошибок {len(errors)}, предупреждений {len(warns)}")
for x in errors + warns:
    print("  ", x)
